import { existsSync, readFileSync } from 'node:fs';
import { join, normalize } from 'node:path';
import { grammar } from '@elastic/textmate-esql';

interface Manifest {
  icon: string;
  files: string[];
  contributes: {
    languages: Array<{
      id: string;
      aliases: string[];
      extensions: string[];
      configuration: string;
    }>;
    grammars: Array<{ language: string; scopeName: string; path: string }>;
  };
}

const PACKAGE_ROOT = join(__dirname, '..', '..');
const manifest: Manifest = JSON.parse(readFileSync(join(PACKAGE_ROOT, 'package.json'), 'utf8'));
const [language] = manifest.contributes.languages;
const [grammarContribution] = manifest.contributes.grammars;

const isPackaged = (path: string): boolean => {
  const [topLevel] = normalize(path).split(/[\\/]/);

  return manifest.files.includes(topLevel);
};

describe('language', () => {
  test('registers ES|QL for the file types the grammar declares', () => {
    expect(language.id).toBe('esql');
    expect(language.aliases).toContain('ES|QL');
    expect(language.extensions).toEqual(grammar.fileTypes.map((type) => `.${type}`));
  });
});

describe('grammar', () => {
  test('is contributed for the registered language', () => {
    expect(grammarContribution.language).toBe(language.id);
  });

  test('uses the scope name generated by @elastic/textmate-esql', () => {
    expect(grammarContribution.scopeName).toBe(grammar.scopeName);
  });
});

describe('packaging', () => {
  test.each([
    ['icon', manifest.icon],
    ['language configuration', language.configuration],
    ['grammar', grammarContribution.path],
  ])('ships the %s referenced by the manifest', (_, path) => {
    expect(isPackaged(path)).toBe(true);
  });

  test.each([
    ['icon', manifest.icon],
    ['language configuration', language.configuration],
  ])('has the committed %s on disk', (_, path) => {
    expect(existsSync(join(PACKAGE_ROOT, path))).toBe(true);
  });
});
