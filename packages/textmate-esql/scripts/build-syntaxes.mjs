/**
 * Generates syntaxes/esql.tmLanguage.json and syntaxes/esql.tmLanguage from
 * the compiled grammar in lib/index.mjs. Run after `tsup`.
 */

import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT_JSON = join(__dirname, '..', 'syntaxes', 'esql.tmLanguage.json');
const OUT_XML = join(__dirname, '..', 'syntaxes', 'esql.tmLanguage');

const { grammar } = await import('../lib/index.mjs');

// ----------------------------------------------------------------------- JSON

writeFileSync(OUT_JSON, JSON.stringify(grammar, null, 2) + '\n');
console.log(`Generated ${OUT_JSON}`);

// ------------------------------------------------------------------ XML plist

const PLIST_HEADER = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by \`yarn build\` from src/index.ts — do not edit by hand -->
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">`;
const PLIST_FOOTER = `</plist>`;

function escapeXml(str) {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function toPlist(value, indent = 1) {
  const pad = '\t'.repeat(indent);

  if (typeof value === 'string') return `<string>${escapeXml(value)}</string>`;
  if (typeof value === 'boolean') return value ? '<true/>' : '<false/>';
  if (typeof value === 'number')
    return Number.isInteger(value) ? `<integer>${value}</integer>` : `<real>${value}</real>`;

  if (Array.isArray(value)) {
    if (value.length === 0) return '<array/>';
    const items = value.map((v) => `${pad}\t${toPlist(v, indent + 1)}`).join('\n');
    return `<array>\n${items}\n${pad}</array>`;
  }

  if (typeof value === 'object' && value !== null) {
    const entries = Object.entries(value)
      .map(([k, v]) => `${pad}\t<key>${escapeXml(k)}</key>\n${pad}\t${toPlist(v, indent + 1)}`)
      .join('\n');
    return `<dict>\n${entries}\n${pad}</dict>`;
  }

  return '<string></string>';
}

writeFileSync(OUT_XML, `${PLIST_HEADER}\n${toPlist(grammar, 0)}\n${PLIST_FOOTER}\n`);
console.log(`Generated ${OUT_XML}`);
